/* USER CODE BEGIN PTD */

/* USER CODE END PTD */

/* Private define ------------------------------------------------------------*/
/* USER CODE BEGIN PD */
#define RX_BUF_SIZE 128
#define LED_DURATION_MS 5000
/* USER CODE END PD */

/* Private macro -------------------------------------------------------------*/
/* USER CODE BEGIN PM */

/* USER CODE END PM */

/* Private variables ---------------------------------------------------------*/
UART_HandleTypeDef huart1;

/* USER CODE BEGIN PV */
/* UART Rx Variables */
uint8_t rx_byte;                        // Biến chứa 1 byte hứng từ ngắt
char rx_buffer[RX_BUF_SIZE];            // Line buffer chứa chuỗi
volatile uint8_t rx_index = 0;          // Vị trí con trỏ ghi vào buffer
volatile bool line_ready = false;       // Cờ báo hiệu đã nhận xong 1 dòng (\r hoặc \n)

/* LED Timer Variables */
uint32_t led_green_start = 0;           // Thời điểm bắt đầu sáng đèn xanh
bool led_green_active = false;          // Đèn xanh đang sáng?
uint32_t led_red_start = 0;             // Thời điểm bắt đầu sáng đèn đỏ
bool led_red_active = false;            // Đèn đỏ đang sáng?

/* Chuỗi mẫu để truyền đi */
const char msg_welcome[] = "\r\n--- UART Command Ready ---\r\n";
const char msg_done[] = "DONE\r\n";
const char msg_error[] = "Error: Buffer Overflow\r\n";
/* USER CODE END PV */

/* Private function prototypes -----------------------------------------------*/
void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_USART1_UART_Init(void);
